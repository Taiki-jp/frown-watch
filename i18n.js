// 日本語と英語の辞書。静的な文は HTML の data-i18n 属性、動的な文は t() で引く
export const LANGS = ["ja", "en"];
const KEY = "fw.lang";

export function getLang() {
  const q = new URLSearchParams(location.search).get("lang"); // ?lang=en で指定できる。選んだ言語は保存される
  if (q && LANGS.includes(q)) return q;
  try { const v = localStorage.getItem(KEY); if (v && LANGS.includes(v)) return v; } catch {}
  return (navigator.language || "").toLowerCase().startsWith("ja") ? "ja" : "en";
}
export function setLang(l) { try { localStorage.setItem(KEY, l); } catch {} }

// t(key, params): {name} を params で置き換える。無い鍵は日本語、それも無ければ鍵そのもの
export function makeT(lang) {
  return (key, params) => {
    let s = STRINGS[lang]?.[key] ?? STRINGS.ja[key] ?? key;
    if (params) for (const [k, v] of Object.entries(params)) s = s.split(`{${k}}`).join(String(v));
    return s;
  };
}
// data-i18n（文字）、data-i18n-html（タグ入り）、data-i18n-title、data-i18n-aria を置き換える
export function applyStatic(root, t) {
  for (const el of root.querySelectorAll("[data-i18n]")) el.textContent = t(el.dataset.i18n);
  for (const el of root.querySelectorAll("[data-i18n-html]")) el.innerHTML = t(el.dataset.i18nHtml);
  for (const el of root.querySelectorAll("[data-i18n-title]")) el.title = t(el.dataset.i18nTitle);
  for (const el of root.querySelectorAll("[data-i18n-aria]")) el.setAttribute("aria-label", t(el.dataset.i18nAria));
}

